const c = new pg.Client({
  host: process.env.DB_HOST || 'localhost',
  port: Number(process.env.DB_PORT) || 5432,
  user: process.env.DB_USER || 'postgres',
  password: process.env.DB_PASSWORD,
  database: process.env.DB_NAME || 'rice_harvester_db',
});
await c.connect();
const { rows } = await c.query('SELECT id, repair_id, filename FROM repair_photos ORDER BY id');
const done = new Set();
let n = 0;
for (const p of rows) {
  const d = byPhoto[p.filename];
  if (!d || done.has(p.repair_id)) continue;
  await c.query('UPDATE repairs SET issue=$2, part=$3, cost=$4 WHERE id=$1', [p.repair_id, d[0], d[1], d[2]]);
  done.add(p.repair_id);
  n++;
}
console.log(`✅ ปรับชื่องานซ่อมให้ตรงกับรูป ${n} รายการ`);
await c.end();
